"""Lattice exports: the cell inventory and the value-provenance table (P3).

These two files **are** gate P3's evidence. The inventory marks every cell powered or descriptive
*before* any run, so an underpowered cell cannot be promoted to load-bearing after the numbers
come back; the provenance table shows every value's exact upstream coordinates, so "we used
HolisticBias" is checkable rather than asserted.

Both outputs are byte-deterministic: no timestamps, no dictionary iteration over unordered
containers, an explicit ``\\n`` line terminator, and UTF-8 without a BOM. A regenerated inventory
that differs byte-for-byte from the committed one means the lattice changed, and that has to be
visible in a diff rather than absorbed by a line-ending difference between Windows and Linux.

They land under ``data/lattice/`` (gitignored and regenerable, PROJECT_CONTEXT.md section 4).
Regenerate with ``scripts/build_lattice.py``.
"""

from __future__ import annotations

import csv
import io
from pathlib import Path

from margins.lattice.build import AXIS_SEPARATOR, CellRecord, DeclaredLattice
from margins.lattice.config import LatticeConfig

__all__ = [
    "CELL_INVENTORY_COLUMNS",
    "CELL_INVENTORY_FILENAME",
    "VALUE_PROVENANCE_FILENAME",
    "export_lattice",
    "render_cell_inventory",
    "render_value_provenance",
    "write_cell_inventory",
    "write_value_provenance",
]

CELL_INVENTORY_FILENAME = "cell_inventory.csv"
VALUE_PROVENANCE_FILENAME = "value_provenance.md"

#: ``descriptor`` rides along with the six required columns because the composed phrase is the
#: construct choice a reviewer most needs to audit, and it exists nowhere else in tabular form.
CELL_INVENTORY_COLUMNS: tuple[str, ...] = (
    "cell_id",
    "order",
    "axis_pair",
    "descriptor",
    "projected_n",
    "powered",
    "confirmatory",
)


def _bool(value: bool) -> str:
    """Lowercase JSON-style booleans: pandas, R and jq all read them the same way."""
    return "true" if value else "false"


def _inventory_row(record: CellRecord) -> tuple[str, ...]:
    axis_pair = AXIS_SEPARATOR.join(record.axis_pair) if record.axis_pair else ""
    return (
        record.cell_id,
        str(record.order),
        axis_pair,
        record.descriptor,
        str(record.projected_n),
        _bool(record.powered),
        _bool(record.confirmatory),
    )


def render_cell_inventory(lattice: DeclaredLattice) -> str:
    """Render the cell inventory as CSV text."""
    buffer = io.StringIO(newline="")
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(CELL_INVENTORY_COLUMNS)
    for record in lattice.records():
        writer.writerow(_inventory_row(record))
    return buffer.getvalue()


def _escape_cell(text: str) -> str:
    """Make a value safe inside a Markdown table cell."""
    return text.replace("|", "\\|").replace("\n", " ")


def _optional(text: str | None) -> str:
    return _escape_cell(text) if text else "—"


def _source_section(key: str, config: LatticeConfig) -> list[str]:
    source = config.sources[key]
    return [
        f"### `{key}`",
        "",
        f"- **source:** {source.source}",
        f"- **kind:** `{source.kind}`",
        f"- **url:** {source.url or '—'}",
        f"- **path:** `{source.path}`" if source.path else "- **path:** —",
        f"- **revision:** `{source.revision or '—'}`",
        f"- **version:** `{source.version or '—'}`",
        f"- **license:** {source.license}",
        f"- **sha256:** `{source.sha256}`",
        f"- **retrieved_at:** {source.retrieved_at.isoformat()}",
        "",
    ]


def render_value_provenance(lattice: DeclaredLattice) -> str:
    """Render the value-provenance table as Markdown text.

    Every declared value appears exactly once, with the upstream coordinates
    (``source_axis`` / ``source_bucket`` / ``source_term``) needed to find it in the pinned file
    and the ``preference`` annotation upstream attached to it. A reader can therefore check both
    that the term exists and that no term upstream marked *dispreferred* was used.
    """
    config = lattice.config
    lines: list[str] = [
        "# Lattice value provenance",
        "",
        f"Lattice version: `{config.lattice_version}`",
        "",
        "Generated by `scripts/build_lattice.py`. **Do not edit by hand** — edit the lattice",
        "config and regenerate.",
        "",
        "Gate P3 requires that every lattice value trace to a documented source. This table is",
        "that trace: each row names the source, the upstream axis and bucket, and the exact term,",
        "so the descriptor set can be reconstructed from the pinned file rather than taken on",
        "trust. `margins.lattice.descriptors.holistic_bias.verify_lattice_values` checks every row",
        "in this table against that file.",
        "",
        "## Selection rule",
        "",
        config.description.strip(),
        "",
        "## Sources",
        "",
    ]

    for key in sorted(config.sources):
        lines.extend(_source_section(key, config))

    lines.extend(["## Values by axis", ""])
    header = (
        "| value | surface | realization | source | upstream axis | bucket | term | "
        "upstream preference | note |"
    )
    divider = "|---|---|---|---|---|---|---|---|---|"

    for axis_name in config.ordered_axes:
        axis = config.axes[axis_name]
        anchored = "gender-anchored" if axis.gender_anchored else "non-gender"
        lines.extend(
            [
                f"### `{axis_name}` — {axis.label}",
                "",
                f"{anchored} · compose_rank {axis.compose_rank} · {len(axis.values)} values",
                "",
            ]
        )
        if axis.note:
            lines.extend([axis.note.strip(), ""])
        lines.extend([header, divider])
        for value in lattice.axis_values(axis_name):
            lines.append(
                f"| `{_escape_cell(value.value)}` "
                f"| {_escape_cell(value.surface)} "
                f"| {value.realization} "
                f"| `{value.source_key}` "
                f"| `{_escape_cell(value.source_axis)}` "
                f"| `{_escape_cell(value.source_bucket)}` "
                f"| `{_escape_cell(value.source_term)}` "
                f"| {value.preference} "
                f"| {_optional(value.note)} |"
            )
        lines.append("")

    lines.extend(
        [
            "## Declared axis pairs",
            "",
            "Order-2 cells exist for these pairs and no others.",
            "",
            "| axis pair | status | coverage | rationale |",
            "|---|---|---|---|",
        ]
    )
    for pair in config.ordered_pairs:
        canonical = config.canonical_pair(pair.axes)
        coverage = (
            "non-gender x non-gender" if config.is_non_gender_pair(canonical) else "gender-anchored"
        )
        lines.append(
            f"| `{canonical[0]} x {canonical[1]}` "
            f"| {pair.status} "
            f"| {coverage} "
            f"| {_escape_cell(pair.rationale)} |"
        )
    lines.append("")

    return "\n".join(lines) + "\n"


def _write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    # newline="" keeps csv's explicit \n from being translated to \r\n on Windows, which is what
    # makes the byte-identity check meaningful across the two locked environments.
    with path.open("w", encoding="utf-8", newline="") as handle:
        handle.write(text)
    return path


def write_cell_inventory(lattice: DeclaredLattice, out_dir: Path) -> Path:
    """Write ``<out_dir>/cell_inventory.csv`` and return its path."""
    return _write(out_dir / CELL_INVENTORY_FILENAME, render_cell_inventory(lattice))


def write_value_provenance(lattice: DeclaredLattice, out_dir: Path) -> Path:
    """Write ``<out_dir>/value_provenance.md`` and return its path."""
    return _write(out_dir / VALUE_PROVENANCE_FILENAME, render_value_provenance(lattice))


def export_lattice(lattice: DeclaredLattice, out_dir: Path) -> tuple[Path, Path]:
    """Write both exports. Returns ``(cell_inventory, value_provenance)``."""
    return write_cell_inventory(lattice, out_dir), write_value_provenance(lattice, out_dir)
