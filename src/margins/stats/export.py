"""Artifacts under ``data/stats/``, plus the human-facing FDR report (P9).

Reuses :func:`margins.metrics.export.write_records` rather than re-implementing the
canonical-sort Parquet writer, so the round-trip guarantee is the same one P6 and P7 already
assert: content equality on a sorted frame, not byte identity, because Parquet embeds writer
metadata.

``effects_corrected.parquet`` is the mirror image of P7's ``effects.parquet``. There the test was
that nulls come back as ``None``, so an uncorrected estimate stays uncorrected across the file
boundary; here it is that ``q``, ``family_size`` and ``correction`` come back PRESENT, because a
corrected estimate that lost its stamp in a round trip would be silently demoted to a number
nobody may cite.

``fdr_report.md`` says in words what a table of q-values cannot: that exploratory pairs carry no
q at all, that a descriptive-only harm type shows a dash rather than a star, and why each of
those is a refusal rather than a negative result.
"""

from __future__ import annotations

from pathlib import Path
from typing import Final

from margins.metrics.export import read_records, write_records
from margins.schemas import EffectEstimate
from margins.stats.analysis import StatsResult
from margins.stats.config import StatsConfig

__all__ = [
    "CLAIMS_FILENAME",
    "DEFAULT_STATS_DIR",
    "DESCRIPTIVE_ONLY_FILENAME",
    "EFFECTS_CORRECTED_FILENAME",
    "FAMILY_FILENAME",
    "FDR_REPORT_MD_FILENAME",
    "export_stats",
    "read_corrected_effects",
    "render_fdr_report_markdown",
]

DEFAULT_STATS_DIR: Final[Path] = Path("data") / "stats"
EFFECTS_CORRECTED_FILENAME: Final[str] = "effects_corrected.parquet"
FAMILY_FILENAME: Final[str] = "family.parquet"
DESCRIPTIVE_ONLY_FILENAME: Final[str] = "descriptive_only.parquet"
CLAIMS_FILENAME: Final[str] = "claims.parquet"
FDR_REPORT_MD_FILENAME: Final[str] = "fdr_report.md"

_EFFECTS_SORT: Final[tuple[str, ...]] = ("benchmark", "model", "harm_type", "_axis_pair", "term")
_FAMILY_SORT: Final[tuple[str, ...]] = (
    "benchmark",
    "model_id",
    "harm_type",
    "axis_a",
    "axis_b",
    "term",
)
_DECISION_SORT: Final[tuple[str, ...]] = ("benchmark", "model_id", "harm_type")
_CLAIMS_SORT: Final[tuple[str, ...]] = _FAMILY_SORT


def read_corrected_effects(path: Path) -> list[EffectEstimate]:
    return read_records(path, EffectEstimate)


def _escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _fmt(value: float | None, digits: int = 4) -> str:
    return "—" if value is None else f"{value:.{digits}f}"


def render_fdr_report_markdown(result: StatsResult, *, config: StatsConfig) -> str:
    """The correction, for humans. Generated; never hand-edited; byte-deterministic."""
    fdr = config.fdr
    lines = [
        "# False-discovery correction over the pre-registered family",
        "",
        f"Stats config: `{config.stats_version}`.",
        "",
        "Generated by `scripts/run_stats.py`. **Do not edit by hand.**",
        "",
        f"- family: **{result.family_size}** tests "
        f"(`{fdr.family_terms}` over the confirmatory axis pairs only)",
        f"- correction: `{fdr.method}` at alpha {fdr.alpha}",
        f"- significant before correction: **{result.n_significant_pre}**",
        f"- significant after correction: **{result.n_significant_post}**",
        f"- exploratory estimates passed through uncorrected: {result.n_exploratory}",
        f"- claimable: {result.n_claimable}, refused: {result.n_refused}",
        "",
        "## What carries no significance claim, and why",
        "",
        "Four rules refuse a claim, and the claim layer RAISES rather than returning false, so a",
        "table that forgets to ask cannot quietly print a star:",
        "",
        "1. **exploratory axis pairs**, outside the pre-registered set and so outside the family;",
        "2. **descriptive-only harm types**, where a scorer's own interaction on known-neutral",
        "   text is comparable to the model's, so model and instrument cannot be told apart;",
        "3. **underpowered cells**, below the pre-registered minimum N;",
        "4. **uncorrected estimates**, which have no q and therefore no claim.",
        "",
        "A refused effect keeps its estimate and its confidence interval and is still reported.",
        "It is not deleted: an absence would be indistinguishable from never having looked.",
        "",
        "## Descriptive-only decisions",
        "",
        "| benchmark | model | harm type | descriptive-only | max drift ratio | over / total |",
        "|---|---|---|---|---:|---:|",
    ]
    for decision in sorted(
        result.descriptive_only, key=lambda d: (d.benchmark, d.model_id, d.harm_type)
    ):
        lines.append(
            f"| {_escape(decision.benchmark)} | `{_escape(decision.model_id)}` "
            f"| {_escape(decision.harm_type)} "
            f"| {'**YES**' if decision.descriptive_only else 'no'} "
            f"| {_fmt(decision.max_ratio, 2)} "
            f"| {decision.n_over_threshold} / {decision.n_comparisons} |"
        )
    lines += [
        "",
        f"Threshold `{config.drift.descriptive_only_ratio:g}`, **pre-registered** (promoted from",
        "P7's placeholder). Recomputed here from the raw magnitudes and never inherited from",
        "P7's own flag, which was computed under the old number.",
        "",
    ]
    if result.drift_disagreements:
        lines += ["### Disagreements with P7's candidate flags", ""]
        lines += [f"- {_escape(line)}" for line in result.drift_disagreements]
        lines += [""]

    lines += [
        "## Claims",
        "",
        "| harm type | axis pair | term | estimate | 95% CI | p | q | q (BY) | status |",
        "|---|---|---|---:|---|---:|---:|---:|---|",
    ]
    for claim in sorted(
        result.claims,
        key=lambda c: (c.benchmark, c.model_id, c.harm_type, c.axis_a, c.axis_b, c.term),
    ):
        significant = claim.claimable and claim.q is not None and claim.q <= fdr.alpha
        status = "**significant**" if significant else claim.status
        lines.append(
            f"| {_escape(claim.harm_type)} | {_escape(claim.axis_a)} x {_escape(claim.axis_b)} "
            f"| `{_escape(claim.term)}` | {claim.estimate:.4f} "
            f"| [{claim.ci_low:.3f}, {claim.ci_high:.3f}] "
            f"| {_fmt(claim.p)} | {_fmt(claim.q)} | {_fmt(claim.q_fdr_by)} | {status} |"
        )
    return "\n".join(lines) + "\n"


def export_stats(
    result: StatsResult, *, config: StatsConfig, out_dir: Path = DEFAULT_STATS_DIR
) -> dict[str, Path]:
    """Write every P9 artifact. Returns ``{name: path}``."""
    out_dir.mkdir(parents=True, exist_ok=True)
    markdown = out_dir / FDR_REPORT_MD_FILENAME
    with markdown.open("w", encoding="utf-8", newline="") as handle:
        handle.write(render_fdr_report_markdown(result, config=config))
    return {
        "effects_corrected": write_records(
            result.corrected, out_dir / EFFECTS_CORRECTED_FILENAME, _EFFECTS_SORT
        ),
        "family": write_records(result.family, out_dir / FAMILY_FILENAME, _FAMILY_SORT),
        "descriptive_only": write_records(
            result.descriptive_only, out_dir / DESCRIPTIVE_ONLY_FILENAME, _DECISION_SORT
        ),
        "claims": write_records(result.claims, out_dir / CLAIMS_FILENAME, _CLAIMS_SORT),
        "fdr_report_md": markdown,
    }
