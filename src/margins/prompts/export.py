#: Raw text goes to JSONL (PROJECT_CONTEXT.md section 6). Versioned in the filename; every record
#: also carries ``template_version``, so the file name and the contents cannot disagree silently.
PROMPTS_FILENAME = "prompts_v1.jsonl"
FILL_AUDIT_FILENAME = "template_fill_audit.md"
PHRASE_AUDIT_FILENAME = "phrase_audit.md"


def _write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    # newline="" keeps the explicit \n from being translated to \r\n on Windows, which is what
    # makes the byte-identity check meaningful across win_amd64 and linux_x86_64.
    with path.open("w", encoding="utf-8", newline="") as handle:
        handle.write(text)
    return path


# --------------------------------------------------------------------------------------
# The prompt file
# --------------------------------------------------------------------------------------


def render_prompts_jsonl(prompts: Sequence[Prompt]) -> str:
    """Render prompts as JSONL, one record per line, in the order given."""
    return "".join(
        json.dumps(
            prompt.model_dump(mode="json"),
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=False,
        )
        + "\n"
        for prompt in prompts
    )


def write_prompts(prompts: Sequence[Prompt], out_dir: Path) -> Path:
    """Write ``<out_dir>/prompts_v1.jsonl`` and return its path."""
    return _write(out_dir / PROMPTS_FILENAME, render_prompts_jsonl(prompts))


# --------------------------------------------------------------------------------------
# The template-fill (slot) audit
# --------------------------------------------------------------------------------------


def render_fill_audit(
    lattice: DeclaredLattice,
    config: PromptSetConfig,
    prompts: Sequence[Prompt],
    files: Sequence[TemplateFile],
) -> str:
    """Render the template-fill audit: the construct choices, the frames, and 20 sampled fills."""
    sample = sample_for_fill_audit(prompts, lattice, FILL_AUDIT_SAMPLE_SIZE)
    group_of = {record.cell_id: audit_group(record) for record in lattice.records()}
    carriers = ", ".join(f"`{carrier.noun}`" for carrier in config.carriers)

    lines: list[str] = [
        "# Template-fill audit",
        "",
        f"Template version: `{config.template_version}`  ",
        f"Lattice version: `{lattice.config.lattice_version}`  ",
        f"Decoding key: `{config.decoding_key}` (TODO(P5): resolved decoding config lands at P5)",
        "",
        "Generated by `scripts/build_prompts.py`. **Do not edit by hand.**",
        "",
        "## Counts",
        "",
        f"- templates: **{len(files)}**",
        f"- cells: **{len(lattice.cells())}** "
        f"({sum(1 for r in lattice.records() if r.order == 1)} order-1, "
        f"{sum(1 for r in lattice.records() if r.order == 2)} order-2)",
        f"- carriers: **{len(config.carriers)}** ({carriers})",
        f"- prompts: **{len(prompts)}** = templates x cells x carriers",
        "",
        "Each prompt is rendered once here. The per-cell rendering count the lattice's power",
        "bookkeeping projects is `|templates| x |samples per prompt|`; the sample count is a P5",
        "decision and the W2 Kaggle timing pilot is what turns it into a budget.",
        "",
        "## Construct choices made in this layer",
        "",
        "**Carrier noun.** P3's `compose_descriptor` stops at a modifier phrase with no carrier",
        "noun, on purpose — attaching one is a P4a decision, made here where its audit trail",
        "belongs. This set uses " + carriers + ". Every obvious alternative is itself an identity",
        "axis: `man`/`woman` carry gender (which would confound the gender axis and gender every",
        "*non*-gender cell), `kid`/`elder` carry age, and any occupational carrier (`nurse`,",
        "`engineer`) carries dense class, gender and race stereotype content — using one would add",
        "an **undeclared second axis of variation** to every cell. `person` is not neutral in an",
        "absolute sense; it is the least axis-loaded option available, which is a weaker claim and",
        "the one made. The register it produces with adjectival gender terms is an open review",
        "item in `phrase_audit.md`.",
        "",
        "**Article.** Chosen by the prompt-set config, not baked into a frame, because the correct",
        "article depends on the composed descriptor (`an older blind person`, `a working-class",
        "Black person`). The rule is the vowel-letter rule plus an explicit override table, and it",
        "**refuses to guess** on the beginnings where that rule is wrong (`eu-`, `u-`, `one-`,",
        "`hon-`). Descriptors are pinned P3 provenance and are never edited to fix an article.",
        "",
        "**Frames.** Neutral elicitation only — no occupation, role, scenario valence, or implied",
        "problem. Identity never appears sentence-initially, so no frame needs to capitalise a",
        "descriptor: `Black` and `Deaf` carry upstream orthography that a capitalisation pass",
        "would silently rewrite.",
        "",
        "## Leakage guard",
        "",
        "Identity cues must appear **only** in the injected slot. Enforced at render time, not by",
        "review: the set of lattice identity terms found in a rendered prompt must equal",
        "**exactly** the set its cell contributes — extra terms mean a frame or slot leaked one,",
        "missing terms mean the injection silently did not happen. Frames are additionally checked",
        "against axis words (`race`, `gender`, `disability`, ...), and a carrier noun may not be a",
        "lattice term. All " + str(len(prompts)) + " prompts in this set pass.",
        "",
        "## Frames",
        "",
        "| template | slots | frame | note |",
        "|---|---|---|---|",
    ]

    slots_by_item = {prompt.item_id: prompt for prompt in prompts}
    for file in files:
        item_id = template_item_id(file.id)
        slots = "—"
        if item_id in slots_by_item:
            slots = ", ".join(f"`{name}`" for name in _slots_of(file, config))
        lines.append(
            f"| `{file.id}` | {slots} | {_escape(file.text)} | {_escape(file.spec.note)} |"
        )

    lines.extend(
        [
            "",
            f"## Slot audit — {len(sample)} sampled fills",
            "",
            "Deterministic and stratified across every declared axis pair and the order-1 cells,",
            "then spread across templates within each group. A head-of-file sample would audit",
            "one template and one pair; this one is re-checkable because it uses no RNG.",
            "",
            "| # | group | cell_id | order | rendered prompt |",
            "|---|---|---|---|---|",
        ]
    )
    for index, prompt in enumerate(sample, start=1):
        cell_id = prompt.cell_id or ""
        group = group_of.get(cell_id, "—")
        order = "1" if group == "order_1" else "2"
        lines.append(
            f"| {index} "
            f"| `{_escape(group)}` "
            f"| `{_escape(cell_id)}` "
            f"| {order} "
            f"| {_escape(prompt.rendered_text)} |"
        )
    lines.append("")

    return "\n".join(lines) + "\n"


def _slots_of(file: TemplateFile, config: PromptSetConfig) -> tuple[str, ...]:
    """Slots a frame references, recomputed from its text so the audit cannot drift."""
    from margins.prompts.render import template_items

    items = template_items(config, (file,))
    slots = items[0].payload.get("slots", ())
    return tuple(str(slot) for slot in slots)


def _escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def write_fill_audit(
    lattice: DeclaredLattice,
    config: PromptSetConfig,
    prompts: Sequence[Prompt],
    files: Sequence[TemplateFile],
    out_dir: Path,
) -> Path:
    """Write ``<out_dir>/template_fill_audit.md`` and return its path."""
    return _write(out_dir / FILL_AUDIT_FILENAME, render_fill_audit(lattice, config, prompts, files))


def write_phrase_audit(
    lattice: DeclaredLattice,
    config: PromptSetConfig,
    prompts: Sequence[Prompt],
    out_dir: Path,
) -> Path:
    """Write ``<out_dir>/phrase_audit.md`` for the first declared frame and carrier."""
    audit_item_id = template_item_id(config.templates[0].id)
    carrier = config.carriers[0].noun
    return _write(
        out_dir / PHRASE_AUDIT_FILENAME,
        _render_phrase_audit(
            lattice, config, prompts, audit_item_id=audit_item_id, carrier=carrier
        ),
    )


def export_prompt_set(
    lattice: DeclaredLattice,
    config: PromptSetConfig,
    prompts: Sequence[Prompt],
    files: Sequence[TemplateFile],
    out_dir: Path,
) -> tuple[Path, Path, Path]:
    """Write all three artifacts. Returns ``(prompts, fill_audit, phrase_audit)``."""
    return (
        write_prompts(prompts, out_dir),
        write_fill_audit(lattice, config, prompts, files, out_dir),
        write_phrase_audit(lattice, config, prompts, out_dir),
    )


# --------------------------------------------------------------------------------------
# Manifest inputs — the provenance hole P3 flagged, closed
# --------------------------------------------------------------------------------------


def prompt_set_inputs(
    *,
    lattice_config_path: Path,
    prompt_config_path: Path,
    files: Sequence[TemplateFile],
) -> dict[str, str]:
    """``{source_name: sha256}`` for every input that decided what the prompt set says.

    Passed to ``write_run_manifest(inputs=...)``. Before P4a a manifest recorded the experiment
    config but **not which identity lattice produced the prompts**, so a run could not be traced
    back to the cell inventory it audited. The lattice digest is keyed by
    :data:`~margins.config.LATTICE_INPUT_KEY` and is the same digest
    ``scripts/build_lattice.py`` prints, so the two artifacts are checkably the same file.
    """
    inputs = {
        LATTICE_INPUT_KEY: file_sha256(lattice_config_path),
        PROMPT_SET_INPUT_KEY: file_sha256(prompt_config_path),
    }
    for file in files:
        inputs[f"{TEMPLATE_INPUT_PREFIX}{file.id}"] = file.sha256
    return inputs
