"""Prompt-set exports: the prompt file, the slot audit, and the manifest input checksums (P4a).

Gate P4a is "byte-identical prompt regeneration from the same config" plus a template-fill audit,
so these writers are held to the same standard as the P3 exports: no timestamps, no iteration over
unordered containers, an explicit ``\\n`` terminator, UTF-8 without a BOM. A regenerated prompt file
that differs byte-for-byte from the previous one means the prompt set changed, and that has to be
visible in a diff rather than absorbed by a line-ending difference between the two locked
environments.

:func:`prompt_set_inputs` is the other half of P4a's job: it builds the ``inputs`` mapping for
``write_run_manifest`` so a manifest records **which lattice, which prompt config, and which
template files** produced a prompt set. Before P4a a manifest could not answer "what identity
lattice was this run built from"; that provenance hole is what this closes.

Outputs land under ``data/prompts/`` — gitignored and regenerable (PROJECT_CONTEXT.md section 4).
"""

