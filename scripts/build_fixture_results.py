"""Write the synthetic stand-in result tables so every P10 figure renders before P11.

    uv run python scripts/build_fixture_results.py

Writes ``results/fixtures/*.csv`` (plus the LaTeX form) from
:mod:`margins.report.fixtures`. **Nothing here is a result.** Every row carries
``data_status=fixture``, every figure drawn from these rows is banner-stamped, and no value
reaches ``results/paper_numbers.json`` -- that file holds numbers the manuscript may cite.

The structure is real: the pre-registered axis pairs and their levels, the confirmatory /
exploratory split, the P6 scorer roster, the pinned model ids, and the extractive paradigm's
measured inability to populate an order-2 grid. Only the estimates are drawn from a seeded RNG,
and the same seed produces the same bytes.

When P11 lands, ``scripts/build_result_tables.py`` writes the same table names into
``results/tables/``, ``scripts/make_figures.py`` prefers that directory automatically, and no
figure code changes.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from margins.lattice.build import DeclaredLattice
from margins.lattice.config import DEFAULT_LATTICE, load_lattice_config
from margins.report.fixtures import build_fixture_tables
from margins.report.tables import (
    DEFAULT_FIXTURE_DIR,
    spec_for,
    write_table_csv,
    write_table_latex,
)
from margins.report.tables import read_table as read_result_table

README = """\
# `results/fixtures/` — synthetic stand-ins, NOT results

Generated by `scripts/build_fixture_results.py`. **Do not cite anything in here.**

The confirmatory run is P11. P10 builds the figures and freezes their code, which requires rows
of the right shape to draw. Every row in every file carries `data_status=fixture`, every figure
built from them carries a visible banner saying so, and no value here is registered in
`results/paper_numbers.json`.

What is real in these files: the pre-registered axis pairs and their levels, the
confirmatory/exploratory split, the two harm types and their scorer rosters, the pinned model
ids, the frame names, the pre-registered drift threshold, and the extractive paradigm's measured
inability to populate an order-2 grid. What is synthetic: every estimate, standard error,
interval, p and q.

When the real run lands, `scripts/build_result_tables.py` writes the same table names into
`results/tables/`, `scripts/make_figures.py` prefers that directory, and the figure code is
unchanged.
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_FIXTURE_DIR)
    parser.add_argument("--lattice", default=DEFAULT_LATTICE)
    parser.add_argument("--no-latex", action="store_true")
    args = parser.parse_args(argv)

    lattice = DeclaredLattice(load_lattice_config(args.lattice))
    tables = build_fixture_tables(lattice)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    with (args.out_dir / "README.md").open("w", encoding="utf-8", newline="") as handle:
        handle.write(README)

    print(f"lattice    {lattice.config.lattice_version}")
    print(f"out        {args.out_dir}\n")
    for name in sorted(tables):
        spec = spec_for(name)
        path = write_table_csv(spec, tables[name], args.out_dir / f"{name}.csv")
        print(f"  {name:<22} {len(tables[name]):>5} rows  -> {path}")
        if not args.no_latex:
            table = read_result_table(name, directory=args.out_dir)
            write_table_latex(table, args.out_dir / f"{name}.tex")

    print(
        "\nFIXTURE DATA. Nothing here is a measurement and nothing here is registered in\n"
        "results/paper_numbers.json. Re-run scripts/build_result_tables.py after P11."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
